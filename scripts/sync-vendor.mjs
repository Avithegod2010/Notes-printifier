/**
 * sync-vendor.mjs — provenance for the vendored binaries in /public.
 *
 * public/ ships binaries copied out of node_modules (pdf.js worker + WASM,
 * Tesseract core + worker + traineddata) plus bundled fonts. Until now they
 * had NO recorded source version/hash, so a Dependabot bump of pdfjs-dist or
 * tesseract.js could silently leave a mismatched worker/WASM pair and break
 * rendering or OCR on some pages.
 *
 * This script:
 *   1. copies the pinned files from node_modules into public/ (the copy
 *      step is opt-in via --copy; by default it only verifies),
 *   2. records source package + resolved version + sha256 + bytes for every
 *      vendored file into public/vendor-manifest.json,
 *   3. with --check, re-hashes public/ and FAILS when any file differs from
 *      the manifest (drifted vendor asset = the bug this prevents).
 *
 * CI runs:  node scripts/sync-vendor.mjs --check
 * Refresh:  node scripts/sync-vendor.mjs --copy && node scripts/sync-vendor.mjs
 */

import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const copy = process.argv.includes('--copy');

const sha256 = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');

// path in public/ → source: 'pkg:<subpath>' (copied from node_modules) or
// 'bundled' (hand-placed asset — recorded for tamper-evidence, not copied).
const SPEC = {
  'pdf.worker.min.mjs': 'pkg:pdfjs-dist/build/pdf.worker.min.mjs',
  'pdfjs/wasm/jbig2.wasm': 'pkg:pdfjs-dist/wasm/jbig2.wasm',
  'pdfjs/wasm/openjpeg.wasm': 'pkg:pdfjs-dist/wasm/openjpeg.wasm',
  'pdfjs/wasm/qcms_bg.wasm': 'pkg:pdfjs-dist/wasm/qcms_bg.wasm',
  'tesseract/worker.min.js': 'pkg:tesseract.js/dist/worker.min.js',
  'tesseract/tesseract-core-lstm.wasm': 'pkg:tesseract.js-core/tesseract-core-lstm.wasm',
  'tesseract/tesseract-core-lstm.wasm.js': 'pkg:tesseract.js-core/tesseract-core-lstm.wasm.js',
  'tesseract/tesseract-core-simd-lstm.wasm': 'pkg:tesseract.js-core/tesseract-core-simd-lstm.wasm',
  'tesseract/tesseract-core-simd-lstm.wasm.js': 'pkg:tesseract.js-core/tesseract-core-simd-lstm.wasm.js',
  'tesseract/tesseract-core-relaxedsimd-lstm.wasm': 'pkg:tesseract.js-core/tesseract-core-relaxedsimd-lstm.wasm',
  'tesseract/tesseract-core-relaxedsimd-lstm.wasm.js': 'pkg:tesseract.js-core/tesseract-core-relaxedsimd-lstm.wasm.js',
  'tesseract/eng.traineddata.gz': 'bundled',
  'tesseract/hin.traineddata.gz': 'bundled',
  'tesseract/tam.traineddata.gz': 'bundled',
  'fonts/NotoSansDevanagari-Regular.ttf': 'bundled',
  'fonts/NotoSansTamil-Regular.ttf': 'bundled',
  'fonts/NotoSansGujarati-Regular.ttf': 'bundled',
  'fonts/NotoSansGurmukhi-Regular.ttf': 'bundled',
  'fonts/NotoSansKannada-Regular.ttf': 'bundled',
  'fonts/NotoSansMalayalam-Regular.ttf': 'bundled',
  'fonts/NotoSansTelugu-Regular.ttf': 'bundled',
  'fonts/NotoSansOriya-Regular.ttf': 'bundled',
};

function pkgVersion(name) {
  try {
    return JSON.parse(readFileSync(join(ROOT, 'node_modules', name, 'package.json'), 'utf8')).version;
  } catch {
    return null;
  }
}

const out = {
  _comment:
    'Generated by scripts/sync-vendor.mjs — DO NOT EDIT BY HAND. ' +
    'Regenerate with: node scripts/sync-vendor.mjs --copy. ' +
    'CI verifies with: node scripts/sync-vendor.mjs --check.',
  generatedAt: new Date().toISOString(),
  packages: {
    'pdfjs-dist': pkgVersion('pdfjs-dist'),
    'tesseract.js': pkgVersion('tesseract.js'),
    'tesseract.js-core': pkgVersion('tesseract.js-core'),
    '@tesseract.js-data/eng': pkgVersion('@tesseract.js-data/eng'),
  },
  files: {},
};

let failures = 0;
for (const [rel, source] of Object.entries(SPEC)) {
  const pubPath = join(ROOT, 'public', rel);
  if (copy && source.startsWith('pkg:')) {
    const src = join(ROOT, 'node_modules', source.slice(4));
    if (!existsSync(src)) {
      console.error(`  ✗ source missing in node_modules: ${source}`);
      failures++;
      continue;
    }
    copyFileSync(src, pubPath);
  }
  if (!existsSync(pubPath)) {
    if (check) {
      console.error(`  ✗ missing: public/${rel} (manifest says it must exist)`);
      failures++;
    }
    continue;
  }
  const hash = sha256(pubPath);
  const bytes = readFileSync(pubPath).length;
  out.files[rel] = { source, sha256: hash, bytes };

  if (check) {
    const prev = readManifest().files[rel];
    if (!prev) {
      console.error(`  ✗ unlisted in manifest: public/${rel}`);
      failures++;
    } else if (prev.sha256 !== hash) {
      console.error(`  ✗ drifted: public/${rel} (manifest ${prev.sha256.slice(0, 12)}… vs actual ${hash.slice(0, 12)}…)`);
      failures++;
    }
  }
}

function readManifest() {
  try {
    return JSON.parse(readFileSync(join(ROOT, 'public/vendor-manifest.json'), 'utf8'));
  } catch {
    return { files: {} };
  }
}

if (check) {
  // Also fail on manifest entries whose file vanished from public/.
  const recorded = readManifest().files ?? {};
  for (const rel of Object.keys(recorded)) {
    if (!existsSync(join(ROOT, 'public', rel))) {
      console.error(`  ✗ manifest lists public/${rel} but the file is gone`);
      failures++;
    }
  }
  if (failures > 0) {
    console.error(`\nvendor check FAILED (${failures} problem(s)). Refresh with: node scripts/sync-vendor.mjs --copy`);
    process.exit(1);
  }
  console.log(`vendor check OK — ${Object.keys(recorded).length} files match the manifest`);
} else {
  writeFileSync(join(ROOT, 'public/vendor-manifest.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(
    `vendor manifest written: ${Object.keys(out.files).length} files ` +
      `(pdfjs-dist ${out.packages['pdfjs-dist']}, tesseract.js ${out.packages['tesseract.js']})`,
  );
}
